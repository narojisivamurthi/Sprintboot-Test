package com.example.employee.service;

import com.example.employee.dto.DesignationRequestDTO;
import com.example.employee.dto.DesignationResponseDTO;
import com.example.employee.entity.Designation;
import com.example.employee.exception.DuplicateResourceException;
import com.example.employee.exception.ResourceNotFoundException;
import com.example.employee.mapper.DesignationMapper;
import com.example.employee.repository.DesignationRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class DesignationServiceTest {

    @Mock
    private DesignationRepository designationRepository;

    @Mock
    private DesignationMapper designationMapper;

    @InjectMocks
    private DesignationService designationService;

    private Designation designation;
    private DesignationRequestDTO requestDTO;
    private DesignationResponseDTO responseDTO;

    @BeforeEach
    void setUp() {
        designation = new Designation("Senior Software Engineer", "SSE");
        designation.setId(1L);

        requestDTO = DesignationRequestDTO.builder()
                .title("Senior Software Engineer")
                .code("SSE")
                .build();

        responseDTO = DesignationResponseDTO.builder()
                .id(1L)
                .title("Senior Software Engineer")
                .code("SSE")
                .build();
    }

    @Test
    @DisplayName("getAllDesignations should return list of DesignationResponseDTOs")
    void getAllDesignations_ShouldReturnList() {
        when(designationRepository.findAll()).thenReturn(List.of(designation));
        when(designationMapper.toResponseDTO(designation)).thenReturn(responseDTO);

        List<DesignationResponseDTO> result = designationService.getAllDesignations();

        assertThat(result).hasSize(1);
        assertThat(result.get(0).getTitle()).isEqualTo("Senior Software Engineer");
    }

    @Test
    @DisplayName("getDesignationById should return DesignationResponseDTO when exists")
    void getDesignationById_Success_ShouldReturnDesignation() {
        when(designationRepository.findById(1L)).thenReturn(Optional.of(designation));
        when(designationMapper.toResponseDTO(designation)).thenReturn(responseDTO);

        DesignationResponseDTO result = designationService.getDesignationById(1L);

        assertThat(result).isNotNull();
        assertThat(result.getId()).isEqualTo(1L);
    }

    @Test
    @DisplayName("getDesignationById should throw ResourceNotFoundException when not found")
    void getDesignationById_NotFound_ShouldThrowException() {
        when(designationRepository.findById(99L)).thenReturn(Optional.empty());

        assertThrows(ResourceNotFoundException.class, () -> designationService.getDesignationById(99L));
    }

    @Test
    @DisplayName("createDesignation should save and return DesignationResponseDTO with provided code")
    void createDesignation_WithProvidedCode_ShouldSave() {
        when(designationRepository.existsByTitle("Senior Software Engineer")).thenReturn(false);
        when(designationRepository.existsByCode("SSE")).thenReturn(false);
        when(designationMapper.toEntity(requestDTO, "SSE")).thenReturn(designation);
        when(designationRepository.save(designation)).thenReturn(designation);
        when(designationMapper.toResponseDTO(designation)).thenReturn(responseDTO);

        DesignationResponseDTO result = designationService.createDesignation(requestDTO);

        assertThat(result).isNotNull();
        assertThat(result.getCode()).isEqualTo("SSE");
        verify(designationRepository, times(1)).save(designation);
    }

    @Test
    @DisplayName("createDesignation should auto-generate code when code is null")
    void createDesignation_WithAutoGeneratedCode_ShouldSave() {
        DesignationRequestDTO noCodeDTO = DesignationRequestDTO.builder()
                .title("Tech Lead")
                .build();

        Designation autoDesig = new Designation("Tech Lead", "TL");
        autoDesig.setId(2L);
        DesignationResponseDTO autoResp = DesignationResponseDTO.builder().id(2L).title("Tech Lead").code("TL").build();

        when(designationRepository.existsByTitle("Tech Lead")).thenReturn(false);
        when(designationRepository.existsByCode("TL")).thenReturn(false);
        when(designationMapper.toEntity(eq(noCodeDTO), eq("TL"))).thenReturn(autoDesig);
        when(designationRepository.save(autoDesig)).thenReturn(autoDesig);
        when(designationMapper.toResponseDTO(autoDesig)).thenReturn(autoResp);

        DesignationResponseDTO result = designationService.createDesignation(noCodeDTO);

        assertThat(result).isNotNull();
        assertThat(result.getCode()).isEqualTo("TL");
    }

    @Test
    @DisplayName("createDesignation should throw DuplicateResourceException when title exists")
    void createDesignation_DuplicateTitle_ShouldThrowException() {
        when(designationRepository.existsByTitle("Senior Software Engineer")).thenReturn(true);

        assertThrows(DuplicateResourceException.class, () -> designationService.createDesignation(requestDTO));
        verify(designationRepository, never()).save(any());
    }

    @Test
    @DisplayName("deleteDesignation should delete designation when found")
    void deleteDesignation_Success_ShouldDelete() {
        when(designationRepository.findById(1L)).thenReturn(Optional.of(designation));
        doNothing().when(designationRepository).delete(designation);

        designationService.deleteDesignation(1L);

        verify(designationRepository, times(1)).delete(designation);
    }
}
